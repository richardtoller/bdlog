#!/usr/bin/env python3
"""Build the bird illustrations used by the app.

Each species image is cropped from a public-domain painting on Wikimedia Commons,
mostly the plates of Archibald Thorburn's "British Birds" (1915-18).
The crop boxes live in tools/bird-image-crops.json as percentages of the source
image: [left, top, right, bottom].

Usage:
    python3 tools/build_images.py            # downloads sources into tools/.cache
    python3 tools/build_images.py --src DIR  # use already-downloaded sources

Outputs img/birds/<slug>.webp and js/images.js.
Needs Pillow (pip install pillow) and network access to commons.wikimedia.org
and upload.wikimedia.org for the first run.
"""
import argparse, json, os, re, sys, time, urllib.parse, urllib.request
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UA = "BirdLogBuild/1.0 (image build script)"
MAX_SIDE = 560
QUALITY = 74
ARTISTS = {
    'British birds': 'Archibald Thorburn',
    'Archibald Thorburn': 'Archibald Thorburn',
    'Keulemans': 'J. G. Keulemans',
    'Ornithologia': 'M. A. Koekkoek',
    'natural history of the ducks': 'A Natural History of the Ducks (1922)',
    'Birds of the world': 'Birds of the World (1898)',
    'Birds of the Rockies': 'Birds of the Rockies (1902)',
    'Frivaldski': 'Imre Frivaldszky',
}


def slug(name):
    return re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')


def local_name(title):
    return re.sub(r'[^A-Za-z0-9._-]+', '_', title[5:])


def get(url, retries=6):
    for i in range(retries):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60) as r:
                return r.read()
        except Exception as e:  # rate limits are common: back off and retry
            if i == retries - 1:
                raise
            print(f'  retry ({e})', file=sys.stderr)
            time.sleep(20 * (i + 1))


def download(titles, dest):
    os.makedirs(dest, exist_ok=True)
    titles = [t for t in titles if not os.path.exists(os.path.join(dest, local_name(t)))]
    for i in range(0, len(titles), 40):
        q = urllib.parse.urlencode({'action': 'query', 'format': 'json', 'prop': 'imageinfo',
                                    'iiprop': 'size|url', 'iiurlwidth': 1920, 'titles': '|'.join(titles[i:i + 40])})
        data = json.loads(get('https://commons.wikimedia.org/w/api.php?' + q))
        for p in data['query']['pages'].values():
            ii = p['imageinfo'][0]
            # Wikimedia only serves standard thumbnail widths; use the original when it is small.
            url = ii['thumburl'] if ii['width'] > 1920 else ii['url']
            url = url.replace('https://thumb.wikimedia.org/', 'https://upload.wikimedia.org/').split('?')[0]
            print('download', p['title'])
            open(os.path.join(dest, local_name(p['title'])), 'wb').write(get(url))
            time.sleep(2)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', default=os.path.join(ROOT, 'tools', '.cache'))
    args = ap.parse_args()
    crops = json.load(open(os.path.join(ROOT, 'tools', 'bird-image-crops.json')))
    download(sorted({c['source'] for c in crops}), args.src)

    out_dir = os.path.join(ROOT, 'img', 'birds')
    os.makedirs(out_dir, exist_ok=True)
    sources, src_index, images = [], {}, {}
    cache = {}
    for c in crops:
        t = c['source']
        if t not in src_index:
            artist = next((a for k, a in ARTISTS.items() if k in t), 'Unknown')
            src_index[t] = len(sources)
            sources.append({'title': t[5:], 'artist': artist})
        if t not in cache:
            cache = {t: Image.open(os.path.join(args.src, local_name(t))).convert('RGB')}
        im = cache[t]
        W, H = im.size
        l, tp, r, b = c['box']
        crop = im.crop((round(l * W / 100), round(tp * H / 100), round(r * W / 100), round(b * H / 100)))
        crop.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)
        fn = slug(c['species']) + '.webp'
        crop.save(os.path.join(out_dir, fn), 'WEBP', quality=QUALITY, method=6)
        images[c['species']] = [fn, src_index[t], crop.width, crop.height]

    with open(os.path.join(ROOT, 'js', 'images.js'), 'w') as f:
        f.write('/* Generated by tools/build_images.py. Do not edit by hand. */\n')
        f.write('/* Public-domain paintings from Wikimedia Commons, cropped per species. */\n')
        f.write('const IMAGE_SOURCES = ' + json.dumps(sources, indent=0) + ';\n')
        f.write('/* name: [file, source index, width, height] */\n')
        f.write('const BIRD_IMAGES = ' + json.dumps(images, indent=0, ensure_ascii=False) + ';\n')
    total = sum(os.path.getsize(os.path.join(out_dir, v[0])) for v in images.values())
    print(f'{len(images)} images, {total / 1e6:.1f} MB')


if __name__ == '__main__':
    main()
